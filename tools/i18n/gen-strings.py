"""从 Strings.resx 生成 C# 强类型访问器。

为什么不用 MSBuild 自带的强类型生成：它产出 `internal class Strings`，而 App 项目
（Lingpane.App）需要直接写字符串，跨程序集访问不到。自己生成一份 public 的即可，
顺便让 check-keys.py 能校验"生成物与 resx 是否同步"。

用法：
    python tools/i18n/gen-strings.py           # 重新生成
    python tools/i18n/gen-strings.py --check   # 只校验，不一致返回 1（CI 用）
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESX = ROOT / "src" / "Lingpane.Core" / "Localization" / "Strings.resx"
OUT = ROOT / "src" / "Lingpane.Core" / "Localization" / "Strings.g.cs"

HEADER = """// <auto-generated>
//   由 tools/i18n/gen-strings.py 从 Strings.resx 生成，请勿手改。
//   改文案请改 resx，然后重新运行该脚本（或 CI 会报出不一致）。
// </auto-generated>

namespace Lingpane.Core.Localization;

/// <summary>
/// 界面文案的强类型访问器。键名拼错编译不过；取值走 <see cref="LocalizationService"/>，
/// 因此属性每次访问都按当前界面语言返回，切换语言后不需要重启或重新取。
/// </summary>
public static class Strings
{
"""

FOOTER = "}\n"


def field_name(key: str) -> str:
    """Resx 键 → C# 属性名：Menu.Open → Menu_Open。"""
    chars = [c if (c.isalnum() or c == "_") else "_" for c in key]
    name = "".join(chars)
    if name[0].isdigit():
        name = "_" + name
    return name


def xml_comment(text: str) -> str:
    """把英文原文放进 XML 注释，便于在代码里按文案搜索。"""
    safe = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    safe = " ".join(safe.split())
    return safe[:120]


def build() -> str:
    tree = ET.parse(RESX)
    items = []
    for data in tree.getroot().findall("data"):
        key = data.get("name")
        if not key:
            continue
        value_el = data.find("value")
        value = (value_el.text or "") if value_el is not None else ""
        items.append((key, value))

    parts = [HEADER]
    for key, value in items:
        parts.append(f"    /// <summary>{xml_comment(value)}</summary>\n")
        parts.append(
            f'    public static string {field_name(key)} => LocalizationService.Instance.Get("{key}");\n'
        )
        if "{" in value and "}" in value:
            # 含占位符的键给一条明确的用法提示，避免调用方拼错参数顺序
            parts.append(
                f"    // 含占位符：string.Format(Strings.{field_name(key)}, ...)\n"
            )
        parts.append("\n")

    parts.append(FOOTER)
    return "".join(parts)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"OUT-OF-DATE: {OUT.relative_to(ROOT)}，请运行 python tools/i18n/gen-strings.py")
            return 1
        print(f"OK: {OUT.relative_to(ROOT)} 与 resx 一致")
        return 0

    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"已生成 {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
